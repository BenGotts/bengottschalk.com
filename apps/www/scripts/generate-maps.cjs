// Generates the SVG outlines in src/content/maps/ from Natural Earth / US Census
// data (via us-atlas and world-atlas). The output is committed, so this only
// needs to run again to change the maps' detail. Run it with:
//
//   npm i --no-save us-atlas@3 world-atlas@2 topojson-client@3 topojson-simplify@3 d3-geo@3 i18n-iso-countries@7
//   node scripts/generate-maps.cjs

const fs = require("node:fs");
const path = require("node:path");
const { feature } = require("topojson-client");
const { presimplify, simplify, quantile } = require("topojson-simplify");
const { geoPath, geoEqualEarth } = require("d3-geo");
const countries = require("i18n-iso-countries");

const OUT = path.join(__dirname, "../src/content/maps");
fs.mkdirSync(OUT, { recursive: true });

// Rounds coordinates in a path to whole units (or tenths), which shrinks it a lot.
const round = (d, digits) => d.replace(/-?\d+\.\d+/g, (n) => Number(n).toFixed(digits).replace(/\.0+$/, ""));

function write(file, comment, typeName, items, viewBox) {
  const body = items.map((item) => `  ${JSON.stringify(item)},`).join("\n");
  fs.writeFileSync(
    path.join(OUT, file),
    `// ${comment}\n// Generated by scripts/generate-maps.cjs; don't edit by hand.\n\nexport const VIEW_BOX = "${viewBox}";\n\nexport const ${typeName} = [\n${body}\n] as const;\n`,
  );
  console.log(file, (fs.statSync(path.join(OUT, file)).size / 1024).toFixed(1), "KB");
}

// US states, already projected (Albers USA, with Alaska and Hawaii inset) to 975×610.
{
  let topo = require("us-atlas/states-albers-10m.json");
  topo = presimplify(topo);
  topo = simplify(topo, quantile(topo, 0.08));
  const toPath = geoPath();
  const states = feature(topo, topo.objects.states).features
    .filter((f) => f.properties.name !== "District of Columbia")
    .map((f) => ({ name: f.properties.name, d: round(toPath(f), 1) }))
    .filter((s) => s.d)
    .toSorted((a, b) => a.name.localeCompare(b.name));
  write("usStates.ts", "The 50 US states as SVG paths (Albers USA projection, from us-atlas).", "US_STATE_SHAPES", states, "0 0 975 610");
}

// Countries (Equal Earth projection, without Antarctica), keyed by ISO 3166-1 alpha-2.
{
  let topo = require("world-atlas/countries-50m.json");
  topo = presimplify(topo);
  topo = simplify(topo, quantile(topo, 0.04));
  const features = feature(topo, topo.objects.countries).features.filter((f) => f.id !== "010" && f.properties.name !== "Antarctica");
  const width = 960;
  const projection = geoEqualEarth().fitWidth(width, { type: "FeatureCollection", features });
  const toPath = geoPath(projection);
  const [[, y0], [, y1]] = toPath.bounds({ type: "FeatureCollection", features });
  const shapes = features
    .map((f) => ({ iso2: f.id ? countries.numericToAlpha2(f.id) : undefined, name: f.properties.name, d: round(toPath(f) ?? "", 0) }))
    .filter((c) => c.iso2 && c.d)
    .map(({ iso2, d }) => ({ iso2, d }))
    .toSorted((a, b) => a.iso2.localeCompare(b.iso2));
  write("worldCountries.ts", "Countries as SVG paths (Equal Earth projection, from world-atlas).", "COUNTRY_SHAPES", shapes, `0 ${Math.floor(y0)} ${width} ${Math.ceil(y1 - y0)}`);
}
