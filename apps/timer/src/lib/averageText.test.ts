import { describe, expect, it } from "vitest";
import type { Solve } from "@bengottschalk/timer-core/solve";
import { averageClipboardText } from "./averageText";

const solve = (timeMs: number, changes: Partial<Solve> = {}): Solve => ({
  id: `s${timeMs}`, eventId: "333", sessionId: "main-333", timeMs, penalty: "none", scramble: "R U R' U'", comment: "",
  startedAt: Date.UTC(2026, 10, 24, 18), endedAt: null, source: "home", competition: null, memoMs: null, fmc: null, multi: null,
  entry: "timer", createdAt: 0, updatedAt: 0, deletedAt: null, ...changes,
});

describe("averageClipboardText", () => {
  it("lays an ao5 out like csTimer, with dropped solves in parentheses", () => {
    const text = averageClipboardText({
      label: "ao5",
      eventId: "333",
      value: 8123,
      solves: [solve(8010), solve(7504, { comment: "PLL skip" }), solve(9876, { penalty: "+2" }), solve(8360, { penalty: "dnf" }), solve(8000)],
      trimmed: [false, true, false, true, false],
      precision: "hundredths",
      generatedAt: new Date(2026, 10, 24, 12).getTime(),
    });
    expect(text).toBe([
      "Generated by Cube Timer on 2026-11-24",
      "ao5: 8.12",
      "",
      "Time List:",
      "1. 8.01   R U R' U'",
      "2. (7.50)[PLL skip]   R U R' U'",
      "3. 11.87+   R U R' U'",
      "4. (DNF)   R U R' U'",
      "5. 8.00   R U R' U'",
    ].join("\n"));
  });

  it("uses thousandths when set, and puts Multi-Blind's scrambles on one line", () => {
    const text = averageClipboardText({
      label: "mo3",
      eventId: "333",
      value: 8123.4,
      solves: [solve(8001, { scramble: "R U\nF D" })],
      trimmed: [false],
      precision: "thousandths",
      generatedAt: new Date(2026, 0, 2, 12).getTime(),
    });
    expect(text.split("\n")[1]).toBe("mo3: 8.123");
    expect(text.split("\n")[4]).toBe("1. 8.001   R U | F D");
  });
});
