import { describe, expect, it } from "vitest";
import { solveValue, type Solve } from "@bengottschalk/timer-core/solve";
import { sessionSummary } from "@bengottschalk/timer-core/summary";
import { formatMean, formatPoints, formatSolve, formatSolveWithPoints, multiPointsText } from "./format";
import { sessionClipboardText } from "./sessionText";

const multi = (solved: number, attempted: number, timeMs: number, changes: Partial<Solve> = {}): Solve => ({
  id: `m${solved}-${attempted}-${timeMs}`, eventId: "333mbf", sessionId: "main-333mbf", timeMs, penalty: "none", scramble: "R U\nF D", comment: "",
  startedAt: Date.UTC(2026, 10, 24, 18), endedAt: null, source: "home", competition: null, memoMs: null, fmc: null, multi: { solved, attempted },
  entry: "timer", createdAt: 0, updatedAt: 0, deletedAt: null, ...changes,
});

describe("Multi-Blind results", () => {
  it("shows cubes and the time to the chosen precision, past ten minutes and an hour", () => {
    expect(formatSolve(multi(6, 7, 3_252_349), "hundredths")).toBe("6/7 54:12.34");
    expect(formatSolve(multi(6, 7, 3_252_349), "thousandths")).toBe("6/7 54:12.349");
    expect(formatSolve(multi(9, 10, 3_723_456), "hundredths")).toBe("9/10 1:02:03.45");
    expect(formatSolve(multi(2, 2, 65_000, { penalty: "+2" }), "hundredths")).toBe("2/2 1:07.00");
  });

  it("shows competition times to the second, and just the cubes when the time isn't known", () => {
    expect(formatSolve(multi(9, 10, 3_456_000, { source: "competition" }), "hundredths")).toBe("9/10 57:36");
    expect(formatSolve(multi(9, 10, 0, { source: "competition" }), "hundredths")).toBe("9/10");
  });

  it("keeps a DNF's cubes and time in brackets", () => {
    expect(formatSolve(multi(2, 7, 3_481_200), "hundredths")).toBe("DNF (2/7 58:01.20)");
    expect(formatSolve(multi(1, 2, 300_000), "hundredths")).toBe("DNF (1/2 5:00.00)");
    expect(formatSolve(multi(7, 7, 3_700_000, { penalty: "dnf" }), "hundredths")).toBe("DNF (7/7 1:01:40.00)");
    expect(formatSolve(multi(0, 0, 0, { penalty: "dnf", multi: null, source: "competition" }), "hundredths")).toBe("DNF");
  });

  it("gives points: solved minus missed, none for a DNF", () => {
    expect(multiPointsText(multi(6, 7, 1))).toBe("5 pts");
    expect(multiPointsText(multi(2, 3, 1))).toBe("1 pt");
    expect(multiPointsText(multi(2, 4, 1))).toBe("0 pts");
    expect(multiPointsText(multi(2, 5, 1))).toBeNull();
    expect(formatPoints(-1)).toBe("-1 pt");
    expect(formatSolveWithPoints(multi(6, 7, 3_252_349), "hundredths")).toBe("6/7 54:12.34 · 5 pts");
    expect(formatSolveWithPoints(multi(1, 3, 600_000), "hundredths")).toBe("DNF (1/3 10:00.00)");
  });

  it("copies a session as results by points, with no averages", () => {
    const solves = [multi(6, 7, 3_252_349), multi(1, 3, 600_000), multi(5, 5, 2_900_000)];
    const text = sessionClipboardText({
      name: "Main", eventId: "333mbf", summary: sessionSummary(solves.map(solveValue)), solves, precision: "hundredths", generatedAt: new Date(2026, 10, 24, 12).getTime(),
    });
    expect(text).toBe([
      "Generated by timer.bengottschalk.com on 2026-11-24",
      "Main · 3x3x3 Multi-Blind",
      "Attempts/Total: 2/3",
      "",
      "Best: 5/5 48:20.00 · 5 pts",
      "Mean points: 5.00",
      "Cubes solved: 12/15",
      "",
      "Result List:",
      "1. 6/7 54:12.34 · 5 pts   R U | F D",
      "2. DNF (1/3 10:00.00)   R U | F D",
      "3. 5/5 48:20.00 · 5 pts   R U | F D",
    ].join("\n"));
  });
});

describe("FMC means", () => {
  it("shows a mean of moves to two places, the WCA way", () => {
    expect(formatMean("333fm", 85 / 3, "hundredths")).toBe("28.33");
    expect(formatMean("333fm", 85 / 3, "thousandths")).toBe("28.33");
    expect(formatSolve({ ...multi(0, 0, 0), eventId: "333fm", multi: null, fmc: { solution: "", moves: 28 } }, "hundredths")).toBe("28");
  });
});
