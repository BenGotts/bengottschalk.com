// The text "Copy" puts on the clipboard for an average, laid out the way
// csTimer exports one, so it pastes cleanly wherever cubers share times.

import type { Solve } from "@bengottschalk/timer-core/solve";
import { localDate } from "@bengottschalk/timer-core/sotd";
import type { Precision } from "@bengottschalk/timer-core/time";
import { formatMean, formatSolve } from "./format";

interface AverageText {
  /** Like "ao5" or "mo3". */
  label: string;
  eventId: string;
  /** The average itself (Infinity for DNF). */
  value: number | null;
  solves: Solve[];
  /** Which of `solves` the average drops; they're shown in parentheses. */
  trimmed: boolean[];
  precision: Precision;
  /** When it's copied (ms), for the date line. */
  generatedAt: number;
}

/**
 * ```
 * Generated by Cube Timer on 2026-11-24
 * ao5: 8.12
 *
 * Time List:
 * 1. 8.01   R U R' …
 * 2. (7.50)   F2 D …
 * ```
 * A comment follows its time in brackets, as in csTimer. Multi-Blind's
 * several scrambles go on one line, separated by " | ".
 */
export function averageClipboardText({ label, eventId, value, solves, trimmed, precision, generatedAt }: AverageText): string {
  const lines = solves.map((solve, i) => {
    const time = formatSolve(solve, precision);
    const shown = trimmed[i] ? `(${time})` : time;
    const comment = solve.comment.trim() ? `[${solve.comment.trim().replace(/\s+/g, " ")}]` : "";
    const scramble = solve.scramble.trim().replace(/\s*\n\s*/g, " | ");
    return `${i + 1}. ${shown}${comment}${scramble ? `   ${scramble}` : ""}`;
  });
  return [
    `Generated by Cube Timer on ${localDate(generatedAt)}`,
    `${label}: ${formatMean(eventId, value, precision)}`,
    "",
    "Time List:",
    ...lines,
  ].join("\n");
}
